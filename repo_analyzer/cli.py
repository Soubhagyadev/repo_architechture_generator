def _load_env() -> None:
    """Load .env if python-dotenv is installed; silently skip when not."""
    try:
        from dotenv import load_dotenv

        load_dotenv()
    except ImportError:
        pass


def _build_llm(config) -> LLMService | None:
    """Create the LLM service when at least one provider has credentials."""
    for provider in config.providers:
        if os.environ.get(provider.env_key):
            return LLMService(config)
    return None


def _analyze_target(
    target: str,
    local: bool,
    refresh: bool,
    config,
    store: CacheStore,
) -> "tuple[RepoAnalyzer, object]":
    """Run analysis handling errors with a friendly CLI message."""
    analyzer = RepoAnalyzer(config, store=store)
    try:
        result = analyzer.analyze(target, is_local=local, refresh=refresh)
    except AnalyzerError as exc:
        console.print(f"[red]error:[/red] {exc}")
        raise typer.Exit(code=1) from exc
    return analyzer, result


def _maybe_llm(config, llm: LLMService | None, *, explicit_off: bool = False) -> None:
    """Warn once when no provider is configured (skip when --no-llm was explicit)."""
    if llm is None and not explicit_off:
        console.print(_NO_LLM_WARNING)


class _FeatureContext:
    """Lifecycle bundle for the standalone feature commands."""

    def __init__(self, config, llm, analyzer, result) -> None:
        self.config = config
        self.llm = llm
        self.analyzer = analyzer
        self.result = result

    def close(self) -> None:
        self.analyzer.close()


@contextmanager
def _feature_ctx(
    target: str,
    local: bool,
    refresh: bool,
    no_llm: bool,
    config_path: Optional[str] = None,
) -> "Iterator[_FeatureContext]":
    """Analyze the target once and hand the pieces to a feature command."""
    _load_env()
    config = load_config(config_path)
    llm = None if no_llm else _build_llm(config)
    _maybe_llm(config, llm, explicit_off=no_llm)
    with CacheStore(config.cache.root + "/cache.sqlite3") as store:
        analyzer, result = _analyze_target(target, local, refresh, config, store)
        ctx = _FeatureContext(config, llm, analyzer, result)
        try:
            yield ctx
        finally:
            ctx.close()


def _feature_out(ctx: _FeatureContext, title: str, sections_html: list[str], payload: dict, out_dir: Path, name: str, quiet: bool) -> Path:
    """Write a standalone HTML file for a feature and print the path."""
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{name}.html"
    subtitle = f"{ctx.result.full_name} @ {ctx.result.ref} · {len(payload.get('changed_files', [])) or ctx.result.file_count} files"
    path.write_text(render_html_report(title, subtitle, sections_html), encoding="utf-8")
    if not quiet:
        console.print(f"[green]saved[/green] {path}")
    return path


def _print_json(payload: dict) -> None:
    console.print_json(json.dumps(payload, ensure_ascii=False, default=str))


def _save_report(out_dir: Path, base: str, title: str, subtitle: str, sections_html: list[str]) -> Path:
    """Write a single-artifact HTML report, return its path."""
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{base}.html"
    path.write_text(render_html_report(title, subtitle, sections_html), encoding="utf-8")
    return path


def _console_overview(result) -> None:
    """Print the rich console overview table."""
    table = Table(title="Overview")
    table.add_column("field")
    table.add_column("value", overflow="fold")
    table.add_row("repository", result.full_name)
    table.add_row("ref", result.ref)
    table.add_row("files", str(result.file_count))
    table.add_row("total LOC", str(result.total_loc))
    table.add_row("primary language", result.primary_language())
    table.add_row("frameworks", ", ".join(result.frameworks) or "-")
    if getattr(result, "stars", 0) or getattr(result, "forks", 0):
        pushed = f" · pushed {result.pushed_at[:10]}" if getattr(result, "pushed_at", "") else ""
        table.add_row("GitHub stats", f"★ {result.stars} · forks {result.forks} · issues {result.open_issues}{pushed}")
    table.add_row("entry points", ", ".join(entry.path for entry in result.entry_points[:4]) or "-")
    table.add_row("parse errors", str(result.parse_errors))
    console.print(table)


def _console_top_files(result, limit: int = 10) -> None:
    """Print the largest source files by LOC."""
    ranked = sorted(result.file_stats.items(), key=lambda item: (-item[1], item[0]))[:limit]
    if not ranked:
        return
    table = Table(title=f"Largest source files (top {min(limit, len(ranked))})")
    table.add_column("file", overflow="fold")
    table.add_column("LOC", justify="right")
    table.add_column("component")
    for path, loc in ranked:
        component = next((c.name for c in result.components if path in c.files), "-")
        table.add_row(path, str(loc), component)
    console.print(table)


def _version_text() -> str:
    """Package version for `version` command."""
    try:
        return importlib_metadata.version("repo-analyzer")
    except importlib_metadata.PackageNotFoundError:
        return "0.1.0 (source)"


@app.command()
def version() -> None:
    """Print the installed repo-analyzer version."""
    console.print(f"repo-analyzer {_version_text()}")


@app.command()
def clean(
    yes: bool = typer.Option(False, "--yes", "-y", help="Skip confirmation"),
    reports: bool = typer.Option(True, "--reports/--no-reports", help="Also delete generated reports (default reports/)"),
) -> None:
    """Delete the analysis cache (and optionally generated reports)."""
    config = load_config()
    targets = [Path(config.cache.root)]
    if reports and Path("reports").is_dir():
        targets.append(Path("reports"))
    removed = []
    for path in targets:
        if not path.exists():
            continue
        if not yes:
            typer.confirm(f"delete {path}/ ?", abort=True)
        shutil.rmtree(path)
        removed.append(str(path))
    console.print(f"[green]removed:[/green] {', '.join(removed) or 'nothing to remove'}")


