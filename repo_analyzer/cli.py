@app.command()
def analyze(
    target: str = typer.Argument(..., help="GitHub URL, owner/repo, or local path with --local"),
    local: bool = typer.Option(False, "--local", help="Treat TARGET as a local directory"),
    refresh: bool = typer.Option(False, "--refresh", help="Ignore cached analysis"),
    out: Optional[str] = typer.Option(None, "--out", help="Directory for md/html reports"),
    config_path: Optional[str] = typer.Option(None, "--config", help="TOML config path"),
    provider: Optional[str] = typer.Option(None, "--provider", help="LLM provider override"),
    no_llm: bool = typer.Option(False, "--no-llm", help="Disable LLM enrichment"),
    quiet: bool = typer.Option(False, "--quiet", "-q", help="Suppress console tables"),
    open_report: bool = typer.Option(False, "--open", help="Open the HTML report in your browser"),
    csv_out: Optional[str] = typer.Option(None, "--csv", help="Export the file inventory (path,language,loc,kb) as CSV"),
) -> None:
    """Full analysis overview with an HTML report containing all sections."""
    _load_env()
    config = load_config(config_path)
    if no_llm:
        llm = None
    else:
        llm = _build_llm(config)
        _maybe_llm(config, llm)
    with CacheStore(config.cache.root + "/cache.sqlite3") as store:
        analyzer, result = _analyze_target(target, local, refresh, config, store)
        if not quiet:
            _console_overview(result)
            _console_top_files(result)
        overview_payload = overview_feature.deterministic_overview(result)
        overview_narrative = overview_feature.llm_overview(result, llm, overview_payload)
        architecture_narrative = llm_architecture(result, llm)
        docs_narrative = llm_documentation(result, llm)
        diagram_notes = llm_diagram_notes(result, llm) if llm else {}
        report = build_full_report(
            result,
            overview_narrative,
            architecture_narrative,
            docs_narrative,
            llm_enabled=llm is not None,
            diagram_notes=diagram_notes,
        )
        base = result.full_name.replace("/", "__").replace(" ", "_").lower() or "report"
        out_dir = Path(out) if out else Path("reports")
        out_dir.mkdir(parents=True, exist_ok=True)
        html_path = out_dir / f"{base}.html"
        html_path.write_text(report, encoding="utf-8")
        if not quiet:
            console.print(f"[green]report written:[/green] {html_path}")
            console.print(f"[dim]{_CAVEAT}[/dim]")
        else:
            console.print(html_path)
        if csv_out:
            csv_path = Path(csv_out)
            csv_path.parent.mkdir(parents=True, exist_ok=True)
            with csv_path.open("w", newline="", encoding="utf-8") as handle:
                writer = csv.writer(handle)
                writer.writerow(["path", "language", "loc", "size_kb"])
                for path in result.all_paths:
                    loc = result.file_stats.get(path, "")
                    writer.writerow(
                        [path, filters.language_for_path(path), loc, round(result.file_sizes.get(path, 0) / 1024, 1)]
                    )
            console.print(f"[green]csv written:[/green] {csv_path}")
        if open_report:
            try:
                webbrowser.open(html_path.resolve().as_uri())
            except Exception:
                console.print("[yellow]could not open a browser; report is at the path above[/yellow]")
        analyzer.close()


@app.command("architecture")
def architecture(
    target: str = typer.Argument(...),
    local: bool = typer.Option(False, "--local"),
    refresh: bool = typer.Option(False, "--refresh"),
    out: Optional[str] = typer.Option(None, "--out"),
    no_llm: bool = typer.Option(False, "--no-llm"),
) -> None:
    """Print architecture diagrams (Mermaid) and the narrative."""
    _load_env()
    config = load_config()
    llm = None if no_llm else _build_llm(config)
    with CacheStore(config.cache.root + "/cache.sqlite3") as store:
        analyzer, result = _analyze_target(target, local, refresh, config, store)
        payload = architecture_payload(result)
        for diagram in payload["diagrams"]:
            console.print(Panel(Syntax(diagram["mermaid"], "text", word_wrap=True), title=diagram["title"]))
        for flow in payload["flows"]:
            console.print(Panel("\n".join(flow["steps"]), title=flow["name"]))
        console.print("[dim]hotspots:[/dim]", ", ".join(f"{row['path']} ({row['imported_by']} importers)" for row in payload["fan_in_out"]))
        if llm:
            narrative = llm_architecture(result, llm)
            if narrative:
                console.print(Panel(narrative.summary, title="Architecture narrative"))
                for flow in narrative.data_flows[:3]:
                    steps = "\n".join(
                        f"- {step.description} (${step.file}:{step.line}$)" if step.file else f"- {step.description}"
                        for step in flow.steps
                    )
                    console.print(Panel(steps, title=f"flow: {flow.name}"))
        if out:
            out_dir = Path(out)
            out_dir.mkdir(parents=True, exist_ok=True)
            flow_html = "".join(
                f"<h3>{flow['name']}</h3><ol class='flow'>"
                + "".join(f"<li>{esc(step)}</li>" for step in flow["steps"])
                + "</ol>"
                for flow in payload["flows"]
            )
            sections_html = [
                section(
                    "Diagrams",
                    "".join(f"<h3>{d['title']}</h3>{mermaid_diagram(d['mermaid'])}" for d in payload["diagrams"]),
                ),
                section("Execution flows", flow_html),
            ]
            if llm and narrative is not None:
                data_section = "".join(
                    f"<h3>{flow.name}</h3><ul>"
                    + "".join(f"<li>{step.description} <i>({step.file}:{step.line})</i></li>" for step in flow.steps)
                    + "</ul>"
                    for flow in narrative.data_flows
                )
                sections_html.insert(1, section("Data flows (narrative)", f"<p>{esc(narrative.summary)}</p>{data_section}"))
            path = out_dir / "architecture.html"
            path.write_text(render_html_report(f"Architecture of {result.full_name}", result.ref, sections_html), encoding="utf-8")
            console.print(f"[green]saved[/green] {path}")
        analyzer.close()


@app.command("docs")
def docs(
    target: str = typer.Argument(...),
    local: bool = typer.Option(False, "--local"),
    out: Optional[str] = typer.Option(None, "--out"),
    no_llm: bool = typer.Option(False, "--no-llm"),
) -> None:
    """Directory responsibilities, tech choices, and execution flow."""
    _load_env()
    config = load_config()
    llm = None if no_llm else _build_llm(config)
    with CacheStore(config.cache.root + "/cache.sqlite3") as store:
        analyzer, result = _analyze_target(target, local, False, config, store)
        payload = documentation_payload(result)
        console.print(Panel("\n".join(f"[bold]{d['path']}[/bold]: {d['purpose']}" for d in payload["directories"]), title="Directories"))
        console.print("[dim]config files:[/dim]", ", ".join(payload["config_files"] or []))
        if llm:
            narrative = llm_documentation(result, llm)
            if narrative:
                console.print(Panel(narrative.summary, title="Codebase documentation"))
                for choice in narrative.tech_choices[:6]:
                    console.print(f"[bold]{choice.technology}[/bold]: {choice.rationale}")
        if out:
            out_dir = Path(out)
            out_dir.mkdir(parents=True, exist_ok=True)
            sections_html = [
                section(
                    "Directories",
                    html_table(
                        ["path", "files", "symbols", "purpose"],
                        [[d["path"], d["files"], d["symbols"], d["purpose"]] for d in payload["directories"]],
                    ),
                ),
                section(
                    "Tech",
                    html_table(
                        ["ecosystem", "count", "sample"],
                        [[t["ecosystem"], t["count"], ", ".join(t["sample"])] for t in payload["tech"]],
                    ),
                ),
                section("Config files", esc(", ".join(payload["config_files"]) or "none")),
            ]
            if llm and narrative is not None:
                sections_html.append(section("Summary", esc(narrative.summary)))
            path = out_dir / "docs.html"
            path.write_text(render_html_report(f"Documentation for {result.full_name}", result.ref, sections_html), encoding="utf-8")
            console.print(f"[green]saved[/green] {path}")
        analyzer.close()


